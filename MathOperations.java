import java.util.*;
class MathOperations{
    public static void main(String[] args){
        int a,b;
        System.out.println("mathematical operations");
        Scanner sc = new Scanner(System.in);
        a=sc.nextInt();
        b=sc.nextInt();
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);

    }
}
